// 场景：幕僚详情默认收起，审批与主要操作始终放在外层，点击按钮不展开详情。
// 数据：Henry 忙碌的任务建议、一个需要确认的问题、一次受限测试审批。
// 执行：量取收起高度、逐项展开、查看原文、修改/发送答案、模拟派发失败、切换语言与主题。
// 预期：三条事项保持紧凑；收起即可审批；仅展开一条；格式化不替换原文；选择与提交分离。
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const output = path.join(__dirname, 'screenshots');
  await fs.mkdir(output, { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1460, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const url = pathToFileURL(path.join(__dirname, 'index.html')).href;
  const head = id => page.locator('[data-toggle="' + id + '"]');
  const body = id => page.locator('#body-' + id);
  const action = (id, name) => page.locator('[data-card="' + id + '"] [data-action="' + name + '"]');
  const capture = name => page.screenshot({ path: path.join(output, name + '.png'), fullPage: true });
  try {
    await page.goto(url);
    assert.equal(await page.locator('[data-toggle]').count(), 3, '必须保留下一步、问答、决策三种事项');
    assert.equal(await page.locator('[data-toggle][aria-expanded="true"]').count(), 0, '默认应全部收起');
    assert.equal(await page.locator('.expanded-body').count(), 0, '未展开时不应常驻详情');
    assert.equal(await action('decision', 'allow').isVisible(), true, '收起时必须能直接看到允许按钮');
    assert.equal(await action('decision', 'reject').isVisible(), true, '收起时必须能直接看到拒绝按钮');
    assert.equal(await action('decision', 'allow').evaluate(el => !!el.closest('[data-toggle],.expanded-body')), false, '审批按钮必须独立于展开触发器与详情区域');
    await action('decision', 'allow').click();
    assert.equal(await head('decision').getAttribute('aria-expanded'), 'false', '直接允许不应顺带展开详情');
    assert.match(await page.locator('[data-card="decision"] .row-result').textContent(), /已允许/, '收起时审批也应显示即时回执');
    assert.equal(await page.locator('[data-card="decision"] .row-result').evaluate(el => el === document.activeElement), true, '收起时审批后焦点应移到外层回执');
    await page.reload();
    await action('decision', 'reject').click();
    assert.equal(await head('decision').getAttribute('aria-expanded'), 'false', '直接拒绝不应顺带展开详情');
    assert.match(await page.locator('[data-card="decision"] .row-result').textContent(), /已拒绝/, '收起时拒绝也应显示即时回执');
    await page.reload();
    assert.equal(await page.locator('.reader-main,.focus-queue,.proto-picker').count(), 0, '新方向不再占用额外详情面板或方案切换区域');
    const height = (await page.locator('.attention-list').boundingBox()).height;
    assert.ok(height <= 210, '三条收起事项总高应不超过 210px；实际为 ' + height);
    await capture('compact-collapsed-dark');
    await head('proposal').click();
    assert.equal(await head('proposal').getAttribute('aria-expanded'), 'true', '点开任务应展开');
    assert.equal(await body('proposal').locator('.task-steps li').count(), 3, '长指令应整理成三条可扫描的任务要点');
    assert.match(await body('proposal').textContent(), /核对证据[\s\S]*修复串扰[\s\S]*补齐测试/, '格式化任务应交代具体行动');
    assert.equal(await page.locator('[data-action="dispatch"]').isDisabled(), true, 'Henry 忙碌时禁止派发');
    assert.equal(await page.locator('.original-copy').isVisible(), false, '原始长指令应默认二级收起');
    await capture('compact-proposal-dark');
    await page.locator('[data-original]').click();
    assert.match(await page.locator('.original-copy').textContent(), /OpenCode parentID/, '必须保留原文中的精确协议字段');
    assert.match(await page.locator('.original-copy').textContent(), /未证实则明确保留为待证/, '摘要不能删除原始不确定性限制');
    await head('question').click();
    assert.equal(await page.locator('[data-toggle][aria-expanded="true"]').count(), 1, '同时只展开一条以控制空间');
    assert.equal(await body('proposal').count(), 0, '打开问答应收起任务');
    assert.equal(await page.locator('input:checked').count(), 0, '推荐项不能被自动选为用户答案');
    assert.equal(await page.locator('[data-action="answer"]').isDisabled(), true, '没有答案时不能发送');
    await page.locator('input[value="trace"]').check();
    assert.equal(await page.locator('[data-receipt]').count(), 0, '点选答案不能自动提交');
    await head('question').click();
    await head('question').click();
    assert.equal(await page.locator('input[value="trace"]').isChecked(), true, '折叠再展开不能丢失草稿');
    await capture('compact-question-dark');
    await page.locator('[data-action="answer"]').click();
    assert.match(await page.locator('[data-receipt]').textContent(), /原始事件/, '回执应展示用户实际发送的答案');
    assert.equal(await page.locator('[data-receipt]').evaluate(el => el === document.activeElement), true, '提交后焦点应留在当前回执');
    await page.locator('[data-action="undo"]').click();
    await page.locator('input[value="custom"]').check();
    assert.equal(await page.locator('[data-action="answer"]').isDisabled(), true, '空的自定义回答不能发送');
    await page.locator('textarea').fill('先追踪父子会话，保留原始事件。');
    await head('decision').click();
    assert.match(await body('decision').textContent(), /仅此一次/, '决策应明确授权范围');
    assert.match(await body('decision').locator('.command').textContent(), /cargo test -p norma/, '必须展示具体命令');
    assert.equal(await body('decision').locator('[data-action="allow"],[data-action="reject"]').count(), 0, '展开后审批按钮仍应留在外层，不得重复渲染');
    await capture('compact-decision-dark');
    await page.locator('[data-action="allow"]').click();
    assert.match(await page.locator('[data-receipt]').textContent(), /已允许/, '审批应有明确回执');
    await page.locator('#language-toggle').click();
    assert.match(await page.locator('[data-receipt]').textContent(), /Only the test command/, '已有回执说明也必须随语言切换');
    await page.locator('#language-toggle').click();
    await page.locator('[data-action="undo"]').click();
    await page.locator('[data-action="reject"]').click();
    assert.match(await page.locator('[data-receipt]').textContent(), /已拒绝/, '拒绝也应有明确回执');
    await head('question').click();
    assert.equal(await page.locator('textarea').inputValue(), '先追踪父子会话，保留原始事件。', '切换事项不能丢失自定义草稿');
    await page.locator('[data-action="answer"]').click();
    assert.match(await page.locator('[data-receipt]').textContent(), /先追踪父子会话，保留原始事件。/, '自定义答案应原样保留');
    await page.locator('[data-action="undo"]').click();
    await page.locator('[data-action="delegate"]').click();
    assert.match(await page.locator('[data-receipt]').textContent(), /已交给 Norma/, '委托应有明确回执');
    await head('proposal').click();
    await page.locator('#scenario').selectOption('failure');
    await page.locator('[data-action="dispatch"]').click();
    await page.waitForSelector('[data-error]');
    assert.equal(await page.locator('[data-action="dispatch"]').isEnabled(), true, '失败后任务保留且可重试');
    await page.locator('#scenario').selectOption('ready');
    await page.locator('[data-action="dispatch"]').click();
    await page.waitForSelector('[data-receipt]');
    assert.match(await page.locator('[data-receipt]').textContent(), /已派给 Henry/, '派发回执应明确接收者');
    await page.locator('[data-action="undo"]').click();
    await page.locator('[data-action="defer"]').click();
    assert.match(await page.locator('[data-receipt]').textContent(), /已暂不采纳/, '暂不采纳应有回执');
    await page.goto(url);
    await head('proposal').focus();
    await page.keyboard.press('Enter');
    assert.equal(await head('proposal').getAttribute('aria-expanded'), 'true', '键盘 Enter 应能展开');
    await page.keyboard.press('Space');
    assert.equal(await head('proposal').getAttribute('aria-expanded'), 'false', '键盘 Space 应能收起');
    assert.equal(await head('proposal').evaluate(el => el === document.activeElement), true, '展开/收起后应保留标题焦点');
    await page.locator('#theme-toggle').click();
    await capture('compact-collapsed-light');
    await head('proposal').click();
    await capture('compact-proposal-light');
    await page.locator('#language-toggle').click();
    assert.match(await page.locator('.overview-heading').textContent(), /Run overview/, '界面应支持英语');
    assert.match(await body('proposal').textContent(), /修复串扰/, '语言切换不能翻译任务原文与用户内容');
    assert.equal(await action('decision', 'allow').isVisible(), true, '英语界面收起时也必须可直接审批');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, '英语按钮不能造成横向溢出');
    await capture('compact-english');
    await page.locator('#language-toggle').click();
    await page.locator('#theme-toggle').click();
    await page.setViewportSize({ width: 446, height: 800 });
    await page.goto(url);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, '446px 窄屏不能横向溢出');
    await capture('compact-narrow-collapsed');
    for (const id of ['proposal', 'question', 'decision']) {
      await head(id).click();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, id + ' 展开时不能横向溢出');
      assert.equal(await head(id).evaluate(el => el.scrollWidth <= el.clientWidth), true, id + ' 标题必须完整保留在容器内');
      await capture('compact-narrow-' + id);
    }
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await head('decision').evaluate(el => getComputedStyle(el).transitionDuration), '0s', '高频展开/收起应即时响应');
    assert.deepEqual(errors, [], '原型不能有脚本或控制台错误');
    await fs.writeFile(path.join(output, 'compact-result.json'), JSON.stringify({ result: 'pass', externalApprovalActions: true, collapsedApprovalTested: true, collapsedHeight: height, themes: 2, locales: 2, narrowWidth: 446, errors, nativeAppValidation: false }, null, 2));
    console.log('PASS: 外层审批、收起直接允许/拒绝、点击不展开、外层回执与焦点、紧凑折叠（' + height + 'px）、双语/主题、窄屏及原有交互。');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
