const fn entry(
    command: ShortcutCommandId,
    category: &'static str,
    title: &'static str,
    hint: &'static str,
    default_keystroke: Option<&'static str>,
) -> ShortcutEntry {
    ShortcutEntry {
        command,
        category,
        title,
        hint,
        default_keystroke,
        editable: true,
    }
}

