//! Windows command keys preserve terminal control input and avoid the system Win modifier.
use super::ShortcutCommandId as Command;

pub(super) const fn key(command: Command) -> Option<&'static str> {
    Some(match command {
        Command::QuitNormaOs => "ctrl-shift-q",
        Command::FocusCommandInput => "ctrl-k",
        Command::NewWindow => "ctrl-shift-n",
        Command::NewWorkspace => "ctrl-n",
        Command::AddProject => "ctrl-shift-a",
        Command::SwitchWorkspace => "ctrl-shift-up",
        Command::PreviousWorkspace => "ctrl-shift-pageup",
        Command::NextWorkspace => "ctrl-shift-pagedown",
        Command::PreviousProject => "ctrl-pageup",
        Command::NextProject => "ctrl-pagedown",
        Command::ExpandSelectedProject => "alt-down",
        Command::ShowProjectOverview => "alt-up",
        Command::ShowWorkspaceDirectory => "ctrl-shift-k",
        Command::NewTerminal => "ctrl-1",
        Command::NewBrowser | Command::NewInfCodeAgent | Command::NewZCodeAgent => return None,
        Command::OpenFileWorkbench => "ctrl-p",
        Command::ShowChanges => "ctrl-shift-g",
        Command::CopyCardContent => "ctrl-shift-c",
        Command::OpenProject => "ctrl-o",
        Command::OpenPreviewFile => "ctrl-shift-o",
        Command::SavePreviewFile => "ctrl-s",
        Command::NewClaudeAgent => "ctrl-2",
        Command::NewCodexAgent => "ctrl-3",
        Command::NewCursorAgent => "ctrl-4",
        Command::NewOpenCodeAgent => "ctrl-5",
        Command::NewGrokAgent => "ctrl-6",
        Command::NewKimiAgent => "ctrl-7",
        Command::NewPiAgent => "ctrl-8",
        Command::NewHermesAgent => "ctrl-9",
        Command::DeleteCard => "ctrl-shift-d",
        Command::ReflowLayout => "ctrl-shift-l",
        Command::ToggleMasterLayout => "ctrl-shift-m",
        Command::ExitFocus => "f6",
        Command::ToggleSettings => "ctrl-,",
        Command::ToggleRunOverview => "ctrl-shift-e",
        Command::ToggleIdeas => "ctrl-shift-i",
        Command::ToggleBrainTrace => "ctrl-shift-b",
        Command::VoiceInteraction => "f8",
        Command::AssignIdeaToCard(1) => "alt-1",
        Command::AssignIdeaToCard(2) => "alt-2",
        Command::AssignIdeaToCard(3) => "alt-3",
        Command::AssignIdeaToCard(4) => "alt-4",
        Command::AssignIdeaToCard(5) => "alt-5",
        Command::AssignIdeaToCard(6) => "alt-6",
        Command::AssignIdeaToCard(7) => "alt-7",
        Command::AssignIdeaToCard(8) => "alt-8",
        Command::AssignIdeaToCard(9) => "alt-9",
        Command::AssignIdeaToNewAgent(0) => "ctrl-0",
        Command::AssignIdeaToNewAgent(1) => "ctrl-shift-0",
        Command::AssignIdeaToNewAgent(2) => "ctrl-shift-2",
        Command::AssignIdeaToNewAgent(3) => "ctrl-shift-3",
        Command::AssignIdeaToNewAgent(4) => "ctrl-shift-4",
        Command::AssignIdeaToNewAgent(5) => "ctrl-shift-5",
        Command::AssignIdeaToNewAgent(6) => "ctrl-shift-6",
        Command::AssignIdeaToNewAgent(7) => "ctrl-shift-7",
        Command::AssignIdeaToNewAgent(8) => "ctrl-shift-8",
        Command::AssignIdeaToNewAgent(9) => "ctrl-shift-9",
        Command::AssignIdeaToCard(_) | Command::AssignIdeaToNewAgent(_) => return None,
    })
}
